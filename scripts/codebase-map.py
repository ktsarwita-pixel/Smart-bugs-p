#!/usr/bin/env python3
"""Generate a cold-start map of the codebase.

This mirrors what Sense's `sense scan` writes to `.sense/summary.md`: the top
namespaces, the hub symbols, the entry points and the conventions, so a new
agent (or human) can orient without reading every file.

Usage: python3 scripts/codebase-map.py > docs/codebase-map.md
"""
from __future__ import annotations

import re
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"

DECL = re.compile(
    r"^\s*(?:export\s+)?(?:default\s+)?"
    r"(?:abstract\s+)?(?:async\s+)?"
    r"(?:class|function|interface|type|enum|const|let|var)\s+"
    r"([A-Za-z_$][\w$]*)"
)
EXPORT = re.compile(r"^\s*export\s+(?:async\s+)?(?:class|function|interface|type|enum|const|let)\s+([A-Za-z_$][\w$]*)")
METHOD = re.compile(r"^\s{2,}(?:public\s+|private\s+|protected\s+|readonly\s+|async\s+|static\s+)*([A-Za-z_$][\w$]*)\s*\(")
IMPORT = re.compile(r"from\s+'([^']+)'")
CLASS_EXTENDS = re.compile(r"\bclass\s+([A-Za-z_$][\w$]*)\s+extends\s+([A-Za-z_$][\w$]*)")


def module_name(path: Path) -> str:
    rel = path.relative_to(ROOT).with_suffix("")
    return ".".join(rel.parts)


def main() -> int:
    files = sorted(SRC.rglob("*.ts"))
    lines: dict[str, int] = {}
    exports: dict[str, list[str]] = {}
    classes: dict[str, str] = {}
    refs: Counter[str] = Counter()
    importers: dict[str, set[str]] = defaultdict(set)

    for file in files:
        text = file.read_text()
        name = module_name(file)
        lines[name] = len(text.splitlines())
        found: list[str] = []
        for line in text.splitlines():
            m = EXPORT.match(line)
            if m and m.group(1) not in found:
                found.append(m.group(1))
        exports[name] = found
        for m in CLASS_EXTENDS.finditer(text):
            classes[m.group(1)] = m.group(2)
        for m in IMPORT.finditer(text):
            target = m.group(1)
            importers[target].add(name)
        for sym in set(re.findall(r"\b[A-Za-z_$][\w$]*\b", text)):
            refs[sym] += 1

    print("# Codebase map")
    print()
    print("Cold-start map of **Sulfur Miners v2** — the shape a new contributor (or")
    print("agent) needs before touching anything. Generated by `scripts/codebase-map.py`;")
    print("the Sense MCP index (`.sense/`) is the live version of this.")
    print()

    print("## Namespaces")
    print()
    print("| Module | Files | Lines |")
    print("| --- | ---: | ---: |")
    groups: dict[str, list[str]] = defaultdict(list)
    for name in lines:
        groups[".".join(name.split(".")[:2])].append(name)
    for group, members in sorted(groups.items()):
        count = len(members)
        total = sum(lines[m] for m in members)
        print(f"| `{group}` | {count} | {total} |")
    print()

    print("## Entry points")
    print()
    for name in ("src/main.ts", "src/game/game.ts", "src/core/input.ts"):
        if name in lines:
            print(f"- `{name}` — {lines[name]} lines")
    print()
    print("`src/main.ts` boots the app: it creates the `Game`, wires the renderer")
    print("and the HUD, and owns the animation loop. Everything else is called from")
    print("`Game.update()`.")
    print()

    print("## Hub symbols")
    print()
    print("Most-referenced exported symbols across the tree — the symbols other")
    print("modules lean on. Counted as modules that reference them.")
    print()
    print("| Symbol | References | Defined in |")
    print("| --- | ---: | --- |")
    exported_total: Counter[str] = Counter()
    home_of: dict[str, str] = {}
    for name, syms in exports.items():
        for sym in syms:
            exported_total[sym] += 1
            home_of.setdefault(sym, name)
    # References counted outside the defining module, so a hub is something other
    # modules actually lean on.
    cross: Counter[str] = Counter()
    for file in files:
        name = module_name(file)
        text = file.read_text()
        for sym in set(re.findall(r"\b[A-Za-z_$][\w$]*\b", text)):
            if home_of.get(sym) and home_of[sym] != name:
                cross[sym] += 1
    hubs = sorted(
        ((cross[s], s) for s in exported_total if len(s) > 3 and cross[s] > 0),
        key=lambda pair: (-pair[0], pair[1]),
    )[:20]
    for count, sym in hubs:
        print(f"| `{sym}` | {count} | `{home_of[sym]}` |")
    print()

    print("## Type map")
    print()
    print("The codebase composes rather than inherits: there are no base classes, so")
    print("each module owns its types. The main ones are listed below.")
    print()
    print("| Type | Kind | Module |")
    print("| --- | --- | --- |")
    kinds: dict[str, str] = {}
    for file in files:
        name = module_name(file)
        for line in file.read_text().splitlines():
            m = re.match(r"^export\s+(?:abstract\s+)?(class|interface|type|enum)\s+([A-Za-z_$][\w$]*)", line)
            if m:
                kinds.setdefault(m.group(2), (m.group(1), name))
    for sym, (kind, name) in sorted(kinds.items()):
        print(f"| `{sym}` | {kind} | `{name}` |")
    print()

    print("## Import edges")
    print()
    print("| Module | Imported by |")
    print("| --- | --- |")
    for name in sorted(lines):
        users = sorted(importers.get(name, set()))
        if users:
            print(f"| `{name}` | {', '.join(f'`{u}`' for u in users)} |")
    print()

    print("## Conventions")
    print()
    print("- One module per concept; the folder name is the namespace (`src/world/`,")
    print("  `src/entities/`, `src/game/`, `src/ui/`, `src/render/`, `src/core/`).")
    print("- Content is data: blocks, items, recipes, upgrades and contracts live in")
    print("  registries and are consumed by `Game`.")
    print("- `Game` is the orchestrator; entities own their own state and physics.")
    print("- The renderer never mutates game state; the game never touches Three.js")
    print("  objects except through `src/render/` helpers.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
